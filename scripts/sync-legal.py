#!/usr/bin/env python3
"""Bind published canonical legal JSON to immutable API consent versions."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "apps/web/src/content/legal"
TARGET = ROOT / "apps/api/internal/legal"
SPECS = [
    ("terms", "terms", "agreement"),
    ("aup", "acceptable-use", "agreement"),
    ("dpa", "dpa", "agreement"),
    ("privacy", "privacy", "notice_received"),
    ("subprocessors", "subprocessors", "notice_received"),
    ("cookies", "cookies", "notice_received"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--version", help="New immutable manifest version")
    parser.add_argument("--adopted", action="store_true", help="Operator adopts these hosted service documents; does not claim legal review")
    args = parser.parse_args()
    existing_path = TARGET / "manifest.json"
    old = json.loads(existing_path.read_text()) if existing_path.exists() else {}
    version = args.version or (old.get("version") if args.check else None)
    if not version or not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._-]{0,99}", version):
        raise SystemExit("Supply a non-empty --version (at most 100 characters).")
    adopted = old.get("adopted", False) if args.check else args.adopted
    documents, files = [], []
    for document_id, name, acknowledgement in SPECS:
        source = SOURCE / (name + ".json")
        raw = source.read_bytes()
        document = json.loads(raw)
        if document.get("id") not in {document_id, name} or not document.get("version") or not document.get("title"):
            raise SystemExit("Invalid canonical document: " + source.name)
        documents.append({"id": document_id, "version": document["version"], "url": "/legal/versions/" + version + "/" + name,
                          "sha256": hashlib.sha256(raw).hexdigest(), "acknowledgement": acknowledgement})
        files.append((TARGET / "documents" / source.name, raw))
        archive = SOURCE / "versions" / version / source.name
        if archive.exists() and archive.read_bytes() != raw:
            raise SystemExit("Archived legal documents are immutable; choose a new version.")
        files.append((archive, raw))
    manifest = {"version": version, "adopted": bool(adopted), "documents": documents}
    versions = sorted({version} | {p.name for p in (SOURCE / "versions").glob("*") if p.is_dir()})
    imports = ['// Generated by scripts/sync-legal.py. Preserve all archived versions.', 'import type { LegalContent } from "@/components/LegalDocument";']
    entries = []
    for i, release in enumerate(versions):
        if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._-]{0,99}", release):
            raise SystemExit("Invalid archived manifest version")
        refs = []
        for j, (_, name, _) in enumerate(SPECS):
            if release != version and not (SOURCE / "versions" / release / (name + ".json")).exists():
                raise SystemExit("Incomplete archived manifest: " + release)
            ref = "v%dDoc%d" % (i, j)
            imports.append('import %s from "./%s/%s.json";' % (ref, release, name))
            refs.append(json.dumps(name) + ': ' + ref)
        entries.append(json.dumps(release) + ': {' + ', '.join(refs) + '}')
    registry = "\n".join(imports) + "\nexport const legalVersions: Record<string, Record<string, LegalContent>> = {\n  " + ",\n  ".join(entries) + "\n};\n"
    files.append((SOURCE / "versions" / "index.ts", registry.encode()))
    if args.check:
        if manifest != old or any(not path.exists() or path.read_bytes() != raw for path, raw in files):
            raise SystemExit("Legal documents differ from the embedded receipt versions; run sync-legal.py with a new version.")
        print("Legal source, embedded bytes and consent manifest match.")
        return
    if old.get("adopted") and old.get("version") == version and manifest != old:
        raise SystemExit("Adopted manifest versions are immutable; choose a new --version.")
    (TARGET / "documents").mkdir(parents=True, exist_ok=True)
    for path, raw in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
    existing_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print("Embedded six canonical legal documents for manifest " + version)


if __name__ == "__main__":
    main()
